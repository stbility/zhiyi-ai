-- 两者的所有权与生命周期完全不同,混在一张表里「谁能改」立刻说不清。
--
-- 工作区挂在组织上而非对话上:同一个项目往往跨多次对话推进,
-- 每次对话都新建工作区,产物就散了。对话通过 workspace_id 关联。
--
-- 本文件与已应用到生产的迁移一致,仅作仓库留档。
