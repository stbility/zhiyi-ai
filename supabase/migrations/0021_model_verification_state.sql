-- =============================================================================
-- 0021 模型的验证状态
--
-- 起因是一次真实事故:英伟达目录 78+ 个模型被无差别导入进用户的选择器,
-- 其中混着视觉、翻译、语音、代码补全、阿拉伯语等根本不能用于中文对话的模型。
-- 用户随手点一个就崩,选中 allam-2-7b(阿拉伯语)得到的是一屏看不懂的字 ——
-- 他报告为「乱码」。最后手工删了 75 个,连 kimi-k2.6、gpt-oss-120b 这些
-- 好模型都误删了,因为**光看模型名根本分不出哪个能用**。
--
-- 根子在于:系统把「服务商目录里有」当成了「用户能用」。
-- 探测明明跑了,结果却只用于报告,不影响模型是否出现在选择器里。
--
-- 这一列把探测结果变成可查询的事实:
--   非空 = 曾经真实调通过一次对话,界面显示「已验证可对话」
--   为空 = 没验证过,界面显示「未验证」,让用户自己判断要不要试
--
-- 与 last_error 配合就能完整表达三种状态,不必再加别的列:
--   last_verified_at 非空          → ✅ 已验证
--   last_verified_at 空 + 有错     → ❌ 上次调用失败(原因在 last_error)
--   两者都空                       → ⚠️ 未验证
-- =============================================================================

alter table public.ai_models
  add column if not exists last_verified_at timestamptz;

comment on column public.ai_models.last_verified_at is
  '最近一次真实对话探测成功的时间。非空表示这个模型确实调得通,
   而不只是出现在服务商的目录里。为空表示未验证,不代表不可用。';
